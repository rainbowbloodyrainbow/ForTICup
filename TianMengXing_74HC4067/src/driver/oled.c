/**
 * @file    oled.c
 * @brief   SSD1306 OLED 128x64 驱动 (Bit-Banged I2C on PA2/PA3)
 *
 * 使用软件 I2C (bit-bang) 避免 SysConfig 依赖，简单可靠。
 * 32MHz CPU 时钟下轻松达到 400kHz I2C。
 */

#include "oled.h"
#include <string.h>
#include <stdio.h>
#include <stdlib.h>

/* ===== 帧缓冲区 ===== */
static uint8_t oled_buf[OLED_WIDTH * OLED_PAGES];

/* ===== 位绊 I2C GPIO ==== */
#define I2C_PORT    GPIOA
#define I2C_SCL_PIN DL_GPIO_PIN_31  /* PA31 */
#define I2C_SDA_PIN DL_GPIO_PIN_28  /* PA28 */

static void i2c_delay(void)
{
    /* ~2.5us for 400kHz I2C */
    delay_cycles(80);
}

static void i2c_scl_lo(void)
{
    DL_GPIO_clearPins(I2C_PORT, I2C_SCL_PIN);
    DL_GPIO_enableOutput(I2C_PORT, I2C_SCL_PIN);
}

static void i2c_scl_hi(void)
{
    DL_GPIO_disableOutput(I2C_PORT, I2C_SCL_PIN);
}

static void i2c_sda_lo(void)
{
    DL_GPIO_clearPins(I2C_PORT, I2C_SDA_PIN);
    DL_GPIO_enableOutput(I2C_PORT, I2C_SDA_PIN);
}

static void i2c_sda_hi(void)
{
    DL_GPIO_disableOutput(I2C_PORT, I2C_SDA_PIN);
}
static uint32_t i2c_sda_read(void) { return DL_GPIO_readPins(I2C_PORT, I2C_SDA_PIN); }

static void i2c_start(void)
{
    i2c_sda_hi();
    i2c_scl_hi();
    i2c_delay();
    i2c_sda_lo();
    i2c_delay();
    i2c_scl_lo();
}

static void i2c_stop(void)
{
    i2c_sda_lo();
    i2c_scl_hi();
    i2c_delay();
    i2c_sda_hi();
    i2c_delay();
}

static bool i2c_write_byte(uint8_t byte)
{
    for (uint8_t i = 0; i < 8; i++) {
        if (byte & 0x80) i2c_sda_hi();
        else             i2c_sda_lo();
        i2c_delay();
        i2c_scl_hi();
        i2c_delay();
        i2c_scl_lo();
        byte <<= 1;
    }
    /* ACK */
    i2c_sda_hi();
    i2c_scl_hi();
    i2c_delay();
    bool ack = (i2c_sda_read() == 0);
    i2c_scl_lo();
    return ack;
}

static void oled_write_cmd(uint8_t cmd)
{
    i2c_start();
    i2c_write_byte((OLED_I2C_ADDR << 1) | 0);  /* 写地址 */
    i2c_write_byte(0x00);                        /* 控制字节: 命令 */
    i2c_write_byte(cmd);
    i2c_stop();
}

static void oled_write_data_buf(const uint8_t *data, uint16_t len)
{
    i2c_start();
    i2c_write_byte((OLED_I2C_ADDR << 1) | 0);  /* 写地址 */
    i2c_write_byte(0x40);                        /* 控制字节: 数据 */
    while (len--) {
        i2c_write_byte(*data++);
    }
    i2c_stop();
}

